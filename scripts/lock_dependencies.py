"""Hash the exact installed dependency closure for Windows x64 CPython 3.14.

Run from a disposable build venv after installing requirements-build.txt:
    python scripts/lock_dependencies.py

Only exact-version binary wheels are downloaded; nothing is installed or run.
Review and commit both lock files. These locks intentionally target Windows,
not Linux/macOS or a different Python ABI.
"""
import argparse
import hashlib
import importlib.metadata as metadata
import os
import platform
import subprocess
import sys
import tempfile
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name, parse_wheel_filename

ROOT = Path(__file__).resolve().parents[1]
RUNTIME_LOCK = "requirements-win-py314.lock"
BUILD_LOCK = "requirements-build-win-py314.lock"


def roots_from_file(path, seen=None):
    path = Path(path).resolve()
    seen = set() if seen is None else seen
    if path in seen:
        raise ValueError("Recursive requirements include")
    seen.add(path)
    out = []
    for raw in path.read_text(encoding="utf-8-sig").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("-r "):
            out.extend(roots_from_file(path.parent / line[3:].strip(), seen.copy()))
            continue
        req = Requirement(line)
        specs = list(req.specifier)
        if req.url or req.extras or len(specs) != 1 or specs[0].operator != "==" or "*" in specs[0].version:
            raise ValueError("Direct requirements must be exact versions without URLs/extras")
        out.append(req)
    return out


def installed_closure(requirements, get_distribution=metadata.distribution):
    """Resolve active dependency markers from the installed target environment."""
    found, pending = {}, list(requirements)
    while pending:
        req = pending.pop()
        if req.marker and not req.marker.evaluate({"extra": ""}):
            continue
        if req.url or req.extras:
            raise ValueError("URL dependencies/extras need an explicit lock policy")
        name = canonicalize_name(req.name)
        dist = get_distribution(name)
        if dist.version not in req.specifier:
            raise ValueError(f"Installed {name} does not satisfy its declared constraint")
        if name in found:
            continue
        found[name] = dist.version
        pending.extend(Requirement(item) for item in (dist.requires or []))
    return dict(sorted(found.items()))


def wheel_hashes(directory, expected):
    hashes = {}
    for path in Path(directory).glob("*.whl"):
        name, version, _build, _tags = parse_wheel_filename(path.name)
        name = canonicalize_name(name)
        if name not in expected or str(version) != expected[name]:
            raise ValueError("Downloaded an unexpected wheel")
        with path.open("rb") as handle:
            digest = hashlib.file_digest(handle, "sha256").hexdigest()
        hashes.setdefault(name, set()).add(digest)
    if set(hashes) != set(expected):
        raise ValueError("Missing binary wheel for a locked dependency")
    return hashes


def render_lock(packages, hashes):
    lines = ["# Generated by scripts/lock_dependencies.py; review before committing.",
             "# Target: Windows x64, CPython 3.14. Binary wheels only.",
             "# Install: python -m pip install --require-hashes --only-binary=:all: -r <this-file>", ""]
    for name, version in sorted(packages.items()):
        values = sorted(hashes[name])
        lines.append(f"{name}=={version} " + " ".join("--hash=sha256:" + item for item in values))
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=ROOT)
    args = parser.parse_args(argv)
    if (sys.platform != "win32" or sys.version_info[:2] != (3, 14)
            or sys.maxsize <= 2 ** 32 or platform.machine().lower() not in ("amd64", "x86_64")):
        parser.error("Generate these locks with Windows x64 CPython 3.14")
    runtime = installed_closure(roots_from_file(ROOT / "requirements.txt"))
    build = installed_closure(roots_from_file(ROOT / "requirements-build.txt"))
    with tempfile.TemporaryDirectory(prefix="discordant-lock-") as td:
        command = [sys.executable, "-m", "pip", "download", "--disable-pip-version-check",
                   "--only-binary=:all:", "--no-deps", "--dest", td]
        command += [f"{name}=={version}" for name, version in build.items()]
        result = subprocess.run(command, capture_output=True, text=True)
        if result.returncode:
            # Index URLs may contain credentials. Do not echo captured pip output.
            raise SystemExit("Wheel download failed; review pip configuration locally and retry.")
        hashes = wheel_hashes(td, build)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    for filename, packages in ((RUNTIME_LOCK, runtime), (BUILD_LOCK, build)):
        target = args.output_dir / filename
        temporary = target.with_suffix(target.suffix + ".tmp")
        temporary.write_text(render_lock(packages, hashes), encoding="utf-8")
        os.replace(temporary, target)
        print(f"Wrote {filename}: {len(packages)} pinned dependencies")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
